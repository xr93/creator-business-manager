import { cookies } from "next/headers";
import { createClient } from "@/utils/supabase/server";
import { signOut } from "@/app/login/actions";
import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { Sidebar } from "@/components/layout/sidebar";
import { MobileHeader, MobileNavigation } from "@/components/layout/mobile-navigation";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const supabase = createClient(await cookies());
  const { data: { user } } = await supabase.auth.getUser();
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {user ? <div className="flex h-screen overflow-hidden" style={{ background: "#F7F8FC" }}>
          <Sidebar />
          <div className="flex-1 flex flex-col overflow-hidden min-w-0">
            <MobileHeader />
            <form action={signOut} className="flex justify-end px-6 py-2 bg-white border-b border-slate-100">
              <button type="submit" className="text-xs font-semibold text-slate-500 hover:text-indigo-600">Sign out</button>
            </form>
            <main className="flex-1 flex flex-col overflow-auto min-h-0">{children}</main>
            <MobileNavigation />
          </div>
        </div> : children}
      </body>
    </html>
  );
}
